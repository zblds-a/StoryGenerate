import {test,expect,Page} from '@playwright/test'
const button=(page:Page,label:string)=>page.locator('uni-button').filter({hasText:new RegExp('^'+label+'$')})
let downstreamRequests:string[]=[]
test.beforeEach(async({page})=>{downstreamRequests=[];page.on('request',r=>{if(r.method()==='POST'&&/\/(production-|performance|tts)/.test(r.url()))downstreamRequests.push(r.url())})})
test.afterEach(()=>{expect(downstreamRequests).toEqual([])})
const token=()=> 'browser-'+Date.now()+'-'+Math.random()
async function begin(page:Page,series=false){
 const auth=token()
 await page.addInitScript(({auth})=>{if(!localStorage.getItem('zj-shell:session:v1'))localStorage.setItem('zj-shell:session:v1',JSON.stringify({type:'object',data:{accessToken:auth,expiresAt:Date.now()+3600000,mode:'live',user:{id:auth,displayName:'故事验收',avatarUrl:'',vipDays:0,balance:0}}}))},{auth})
 await page.goto('/#/pages/story-session/index')
 if(series)await button(page,'长剧·先写首集').click()
 await button(page,'阿青').click()
 await button(page,'小墨').click()
 await button(page,'开始一起创作').click()
 await page.locator('uni-button.direction').first().click()
 await expect(page.getByText('按这个方向写剧本',{exact:true})).toBeVisible()
 return auth
}
test('only choices: short story, live intervention, reconnect, confirm, export, preserved versions',async({page})=>{
 await begin(page)
 await button(page,'开放').click()
 await expect(page.getByText('按这个方向写剧本',{exact:true})).toBeVisible()
 await button(page,'按这个方向写剧本').click()
 await button(page,'更温暖').click()
 await expect(button(page,'确认调整范围')).toBeVisible()
 await button(page,'确认调整范围').click()
 await expect(page.getByText('按这个方向写剧本',{exact:true})).toBeVisible()
 await button(page,'按这个方向写剧本').click()
 await page.reload()
 await expect(page.getByText('确认当前剧本',{exact:true})).toBeVisible({timeout:25000})
 await button(page,'确认当前剧本').click()
 await expect(page.getByText('剧本已确认',{exact:true})).toBeVisible()
 const download=page.waitForEvent('download')
 await button(page,'导出剧本与背景规格').click()
 expect((await download).suggestedFilename()).toMatch(/^story-.*.json$/)
 await button(page,'第1幕').click()
 await button(page,'只改这一幕').click()
 await button(page,'更轻松').click()
 await button(page,'确认调整范围').click()
 await expect(page.getByText('按这个方向写剧本',{exact:true})).toBeVisible()
 await button(page,'按这个方向写剧本').click()
 await expect(page.getByText('确认当前剧本',{exact:true})).toBeVisible({timeout:25000})
 await expect(page.getByText(/已保留 1 个历史确认版本/)).toBeVisible()
 await page.screenshot({path:'evidence/story-session-desktop.png',fullPage:true})
})
test('series replans count and creates only the next episode',async({page})=>{
 await begin(page,true)
 await button(page,'3 集').click()
 await expect(page.getByText('重新规划集数（当前 3 集）',{exact:true})).toBeVisible()
 await button(page,'按这个方向写剧本').click()
 await expect(page.getByText('确认当前剧本',{exact:true})).toBeVisible({timeout:25000})
 await button(page,'确认当前剧本').click()
 await button(page,'继续下一集').click()
 await expect(page.getByText('第 2 集 · 已完成 0 / 2 幕',{exact:true})).toBeVisible()
 await button(page,'按这个方向写剧本').click()
 await expect(page.getByText('确认当前剧本',{exact:true})).toBeVisible({timeout:25000})
 await button(page,'确认当前剧本').click()
 await expect(page.getByText('剧本已确认',{exact:true})).toBeVisible()
})
test('mobile options and cancel persist after refresh without media actions',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await begin(page)
 await button(page,'按这个方向写剧本').click()
 await button(page,'取消生成').click()
 await expect(page.getByText('已取消',{exact:true})).toBeVisible()
 await page.reload()
 await expect(page.getByText('已取消',{exact:true})).toBeVisible()
 await expect(page.getByText('查看作品制作',{exact:true})).toHaveCount(0)
 await page.screenshot({path:'evidence/story-session-mobile.png',fullPage:true})
})
